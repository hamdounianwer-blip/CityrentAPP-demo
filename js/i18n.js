// ── translate(key) : retourne la traduction pour la langue active, ou
// la clé elle-même si elle manque (jamais d'écran cassé / vide) ──
function translate(key){
  let dict = I18N_DICT[window._currentLang] || I18N_DICT.en;
  return (dict && dict[key] !== undefined) ? dict[key] : (I18N_DICT.en[key] || key);
}

// ── applyI18n() : parcourt tous les éléments [data-i18n] visibles à cet
// instant et applique la traduction. Rejoué à chaque changement de
// langue ET une fois au démarrage. ──
function applyI18n(){
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    let key = el.getAttribute('data-i18n');
    el.textContent = translate(key);
  });
  // Sidebar en RTL seulement — pas le reste de l'app pour ce pilote.
  let sidebar = document.querySelector('.sidebar');
  if(sidebar) sidebar.setAttribute('dir', window._currentLang === 'ar' ? 'rtl' : 'ltr');
  let langBtn = document.getElementById('lang-btn');
  let langLabel = document.getElementById('lang-btn-label');
  if(langBtn) langBtn.setAttribute('data-lang', window._currentLang);
  if(langLabel) langLabel.textContent = (window._currentLang === 'ar') ? 'EN' : 'AR';
}

// ── toggleLanguage() : bascule EN <-> AR, sauvegarde le choix ──
// FIX (2026-07) : applyI18n() seul ne traduit que les éléments statiques
// [data-i18n] déjà présents dans le HTML. Tout le contenu généré
// dynamiquement en JS (cartes du Dashboard, tableaux Daily Rentals,
// Payments...) est construit par les fonctions render*() des modules, qui
// appellent translate() au moment du rendu — donc si on ne les relance pas,
// ce contenu reste dans l'ancienne langue jusqu'au prochain refresh de page.
// On appelle donc refreshAll() (core.js) juste après pour tout reconstruire
// immédiatement dans la nouvelle langue, sans que l'utilisateur ait besoin
// de recharger la page.
function toggleLanguage(){
  window._currentLang = (window._currentLang === 'ar') ? 'en' : 'ar';
  try { localStorage.setItem('fleetpro_lang', window._currentLang); } catch(e){}
  applyI18n();
  if(typeof applyDepI18n === 'function') applyDepI18n();
  if(typeof refreshAll === 'function') refreshAll();
  // Revenue Stats (Overview/Daily/Monthly/Yearly/Vehicle/Profit/By Category) is built by
  // switchRevenueTab()/render*Stats(), which are NOT called by refreshAll() above — without
  // this, whichever revenue-stats tab is open stays in the old language until the user
  // navigates away and back. Only re-render if that page has actually been loaded once
  // (its DOM exists), otherwise there is nothing to refresh yet.
  if(typeof switchRevenueTab === 'function' && typeof g_revenueTab !== 'undefined' && document.getElementById('revenue-daily-section')){
    try { switchRevenueTab(g_revenueTab); } catch(e){ console.warn('[i18n] switchRevenueTab refresh failed', e); }
  }
  // Same issue for the Cheque tab in Expenses (DEPENCE) — its rows/status badges/summary
  // cards are built by renderDepChequeList(), not by applyDepI18n() (which only relabels
  // the static tab buttons).
  let depChequeTab = document.getElementById('dep-tab-cheque');
  if(typeof renderDepChequeList === 'function' && depChequeTab && depChequeTab.style.display !== 'none'){
    try { renderDepChequeList(); } catch(e){ console.warn('[i18n] renderDepChequeList refresh failed', e); }
  }
  if(typeof refreshMonthCalendarLabels === 'function') refreshMonthCalendarLabels();
  // GPS Map (module-gps-map.js) : idem que Revenue Stats/Cheques ci-dessus —
  // pas touché par refreshAll(), et son contenu (pins/panneaux/popups) n'est
  // reconstruit que par renderGpsMap() (poll 30s tant que l'onglet Map est
  // ouvert). Sans ce hook, la carte reste dans l'ancienne langue jusqu'au
  // prochain cycle de poll si on bascule la langue pendant qu'elle est déjà
  // affichée.
  if(typeof renderGpsMap === 'function' && window._gpsView === 'map') renderGpsMap();
  _applyDigitModeForCurrentLang();
}
