// ── Chiffres arabes-indiens (٠١٢٣٤٥٦٧٨٩) : conversion automatique de
// tout chiffre visible dans le DOM quand la langue active est 'ar'.
// Fonctionne aussi pour le contenu généré dynamiquement (cartes,
// tableaux, modales...) grâce à un MutationObserver, sans avoir à
// toucher chaque fonction render*() des modules. ──
const _AR_DIGIT_MAP = {'0':'٠','1':'١','2':'٢','3':'٣','4':'٤','5':'٥','6':'٦','7':'٧','8':'٨','9':'٩'};
const _LATIN_DIGIT_MAP = {'٠':'0','١':'1','٢':'2','٣':'3','٤':'4','٥':'5','٦':'6','٧':'7','٨':'8','٩':'9'};

function toArabicDigits(input){
  if(input === null || input === undefined) return input;
  return String(input).replace(/[0-9]/g, function(d){ return _AR_DIGIT_MAP[d]; });
}
window.toArabicDigits = toArabicDigits;

function toLatinDigits(input){
  if(input === null || input === undefined) return input;
  return String(input).replace(/[٠-٩]/g, function(d){ return _LATIN_DIGIT_MAP[d]; });
}
window.toLatinDigits = toLatinDigits;

const _DIGIT_SKIP_TAGS = { SCRIPT:1, STYLE:1, TEXTAREA:1, NOSCRIPT:1 };

function _convertDigitsInNode(node){
  if(!node) return;
  if(node.nodeType === 3){
    if(node.nodeValue && /[0-9]/.test(node.nodeValue)){
      node.nodeValue = toArabicDigits(node.nodeValue);
    }
    return;
  }
  if(node.nodeType !== 1) return;
  if(_DIGIT_SKIP_TAGS[node.tagName]) return;
  if(node.hasAttribute && node.hasAttribute('data-no-digit-convert')) return;
  // Champs de saisie : on convertit uniquement s'ils sont en lecture
  // seule / désactivés (affichage pur), jamais un champ éditable, pour
  // ne jamais corrompre une valeur numérique saisissable ou stockée.
  if(node.tagName === 'INPUT'){
    const type = (node.getAttribute('type') || 'text').toLowerCase();
    if((node.readOnly || node.disabled) && type !== 'number' && node.value && /[0-9]/.test(node.value)){
      node.value = toArabicDigits(node.value);
    }
    return;
  }
  for(let child = node.firstChild; child; child = child.nextSibling){
    _convertDigitsInNode(child);
  }
}

function convertDigitsToArabic(root){
  _convertDigitsInNode(root || document.body);
}
window.convertDigitsToArabic = convertDigitsToArabic;

let _digitObserver = null;
function _startDigitObserver(){
  if(_digitObserver || !document.body) return;
  _digitObserver = new MutationObserver(function(mutations){
    if(window._currentLang !== 'ar') return;
    for(let i=0; i<mutations.length; i++){
      const m = mutations[i];
      if(m.type === 'characterData'){
        _convertDigitsInNode(m.target);
      } else if(m.type === 'childList'){
        m.addedNodes.forEach(function(n){ _convertDigitsInNode(n); });
      } else if(m.type === 'attributes' && m.target.tagName === 'INPUT'){
        _convertDigitsInNode(m.target);
      }
    }
  });
  _digitObserver.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['value']
  });
}
function _stopDigitObserver(){
  if(_digitObserver){ _digitObserver.disconnect(); _digitObserver = null; }
}

function _applyDigitModeForCurrentLang(){
  if(window._currentLang === 'ar'){
    convertDigitsToArabic(document.body);
    _startDigitObserver();
  } else {
    _stopDigitObserver();
  }
}
window._applyDigitModeForCurrentLang = _applyDigitModeForCurrentLang;

if(document.readyState === 'loading'){
  document.addEventListener('DOMContentLoaded', _applyDigitModeForCurrentLang);
} else {
  _applyDigitModeForCurrentLang();
}

// ── i18nMonthNames() : retourne le tableau des 12 noms de mois dans la
// langue active. Remplace les tableaux `const monthNames=[...]` codés en
// dur dans les modules (module-daily-rentals.js, module-month-picker.js).
// Utilisation : `i18nMonthNames()[mo-1] + ' ' + yr` pour afficher
// « July 2026 » (EN) ou « يوليو 2026 » (AR). ──
function i18nMonthNames(){
  const lang = window._currentLang || 'en';
  const out = [];
  for(let i=0; i<12; i++){
    out.push(translate('month.' + i));
  }
  return out;
}
window.i18nMonthNames = i18nMonthNames;

// ── i18nPlural(key1, key2, n) : renvoie key1 si n<=1, sinon key2.
// Helper pour gérer les pluriels (1 rental / 2 rentals) sans dupliquer
// la logique dans chaque module. ──
function i18nPlural(singularKey, pluralKey, n){
  return (Number(n) > 1 ? translate(pluralKey) : translate(singularKey));
}
window.i18nPlural = i18nPlural;
